/* Service Worker - Montería Running Team (PWA)
   Estrategia: red primero (para recibir actualizaciones), con caché de
   respaldo para que la app abra sin conexión. No intercepta envíos POST
   (los marcajes al Apps Script) ni dominios externos (Google, fuentes). */
var CACHE = 'mrt-pwa-v1';
var ASSETS = [
  './',
  './index.html',
  './manifest.json',
  './icon-192.png',
  './icon-512.png',
  './apple-touch-icon.png'
];

self.addEventListener('install', function (e) {
  e.waitUntil(
    caches.open(CACHE)
      .then(function (c) { return c.addAll(ASSETS); })
      .then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (e) {
  e.waitUntil(
    caches.keys().then(function (ks) {
      return Promise.all(ks.map(function (k) { if (k !== CACHE) return caches.delete(k); }));
    }).then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('fetch', function (e) {
  var req = e.request;
  if (req.method !== 'GET') { return; }                 // deja pasar POST (marcajes al Apps Script)
  var url = new URL(req.url);
  if (url.origin !== self.location.origin) { return; }  // no intercepta Google ni fuentes externas
  e.respondWith(
    fetch(req).then(function (res) {
      var copy = res.clone();
      caches.open(CACHE).then(function (c) { c.put(req, copy); });
      return res;
    }).catch(function () {
      return caches.match(req).then(function (r) { return r || caches.match('./index.html'); });
    })
  );
});
